#!/usr/bin/env bash
# 自动生成 alembic 迁移文件 (alembic revision --autogenerate).
#
# 用法:
#   bash scripts/db_autogen.sh "add xxx column"
#
# 工作流:
#   1. 改 model (app/models/*.py)
#   2. 跑这个脚本生成迁移文件
#   3. REVIEW 文件内容, 删掉 false positive (autogenerate 对 server_default 探测经常有误报)
#   4. 跑 `bash scripts/db_migrate.sh` 应用
#   5. 跑 `bash scripts/db_check.sh` 确认 clean
#
# 注意:
#   - autogenerate 不是银弹, 复杂迁移 (data migration / 多步 DDL) 仍需手写
#   - 不要在生产 DB 上直接跑, 先在 staging 验证
set -euo pipefail
cd "$(dirname "$0")/.."

MSG="${1:-autogenerated schema sync}"

docker compose exec -T app alembic revision --autogenerate -m "$MSG"
echo "✓ migration generated — review alembic/versions/ before running upgrade"